/* Amazon Bio Discovery stage (v3.0): the closed-loop agentic antibody discovery pipeline.
   Five scroll/rail-driven states matching the chapter's five steps:
     0 Before: 6 to 12 months conventional discovery vs. weeks in the MSK launch campaign.
     1 Ask: Interactive target protein ribbon — tap any of the 5 ranked hotspot pockets.
     2 Design: Three distinct generative models across 2,000 GPUs in 2 AWS regions -> 288,000 nanobodies.
     3 Judge: Interactive multi-objective Pareto frontier — peel Front 1, Front 2, or 100,000 kept.
     4 Test: Closed wet-lab loop — 100,000 DNA (Twist) -> 116 binding assays -> 46 confirmed binders -> checked before retraining.
   All numbers strictly match the published Bio Discovery chapter. Reduced motion gets immediate state cuts. */
export function wire(st, ctx) {
  const { $$, live } = ctx;

  // Step 01 Ask: interactive ranked hotspot pockets on target ribbon
  const HOTSPOTS = [
    { id: '1', label: 'Region 1 · Top ranked', note: 'Exposed loop pocket; bioinformatics tools + language model rationale.' },
    { id: '2', label: 'Region 2 · High score', note: 'Secondary solvent-accessible cleft with strong structural evidence.' },
    { id: '3', label: 'Region 3 · Candidate', note: 'Conserved chain interface ranked in the agent’s top five regions.' },
    { id: '4', label: 'Region 4 · Candidate', note: 'Alternate binding face evaluated against known structural motifs.' },
    { id: '5', label: 'Region 5 · Top-5 cutoff', note: 'On known antibody-target pairs, top-five regions overlapped the true site ~80% of the time.' },
  ];
  const hsNodes = $$('.bd-hs', st);
  const hsOut = $$('.bd-hs-out', st);
  function pickHotspot(id, announce) {
    const h = HOTSPOTS.find(x => x.id === String(id)) || HOTSPOTS[0];
    hsNodes.forEach(n => {
      const on = n.dataset.hs === h.id;
      n.classList.toggle('on', on);
      n.setAttribute('aria-pressed', on ? 'true' : 'false');
    });
    hsOut.forEach(o => { o.textContent = `${h.label} — ${h.note}`; });
    if (announce && live) live(`${h.label}. ${h.note}`);
  }
  hsNodes.forEach(n => {
    const act = () => pickHotspot(n.dataset.hs, true);
    n.addEventListener('click', act);
    n.addEventListener('keydown', e => { if (e.key === 'Enter' || e.key === ' ') { e.preventDefault(); act(); } });
  });
  pickHotspot('1', false);

  // Step 03 Judge: interactive Pareto frontier peel (Front 1 / Front 2 / 100,000 kept)
  const FRONTS = {
    '1': 'Front 1 (Kept first): non-dominated designs with the strongest trade-off across five scores.',
    '2': 'Front 2 (Kept next): next-best trade-off layer added once Front 1 is selected.',
    'all': 'Outer fronts kept in sequence until 100,000 candidates remained for DNA synthesis.',
  };
  const pfBtns = $$('.bd-pf-ctrl button[data-pf]', st);
  const pfOut = $$('.bd-pf-out', st);
  function pickFront(mode, announce) {
    st.dataset.pf = mode;
    pfBtns.forEach(b => b.setAttribute('aria-checked', b.dataset.pf === mode ? 'true' : 'false'));
    pfOut.forEach(o => { o.textContent = FRONTS[mode] || FRONTS.all; });
    if (announce && live && FRONTS[mode]) live(FRONTS[mode]);
  }
  pfBtns.forEach(b => b.addEventListener('click', () => pickFront(b.dataset.pf, true)));
  pickFront('all', false);

  // Interactive hover/focus readout on bottom launch funnel (if present on page)
  const funnelBox = document.querySelector('.m14-funnel-wrap');
  if (funnelBox) {
    const read = funnelBox.querySelector('.m14-f-read');
    const items = Array.from(funnelBox.querySelectorAll('[data-fstage]'));
    const F_TEXT = {
      '0': '288,000 nanobody designs generated by three AI models on 2,000 GPUs in two AWS regions.',
      '1': '100,000 designs selected across five scores and made as DNA by Twist Bioscience.',
      '2': '116 candidates advanced from the first lab screen to individual binding tests.',
      '3': '46 of the 116 tested candidates were confirmed to bind the target (~40% confirmation rate).',
    };
    const showF = k => {
      items.forEach(el => el.classList.toggle('on', el.dataset.fstage === k));
      if (read && F_TEXT[k]) read.textContent = F_TEXT[k];
    };
    items.forEach(el => {
      el.addEventListener('mouseenter', () => showF(el.dataset.fstage));
      el.addEventListener('focus', () => showF(el.dataset.fstage));
      el.addEventListener('click', () => showF(el.dataset.fstage));
    });
    showF('3');
  }

  return {
    to(s) {
      const k = Math.max(0, Math.min(4, parseInt(s, 10) || 0));
      st.dataset.s = String(k);
    },
  };
}
